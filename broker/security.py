def public_error_code(error, fallback="LOCAL_DATA_OR_IO_ERROR"):
    message = str(error)
    return message if message in PUBLIC_ERROR_CODES else fallback


def private_database(path, *, exclusive=False):
    path = Path(path)
    flags = os.O_RDWR | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0)
    if exclusive:
        flags |= os.O_EXCL
    try:
        descriptor = os.open(path, flags, 0o600)
        try:
            os.fchmod(descriptor, 0o600)
        finally:
            os.close(descriptor)
    except OSError:
        raise SafetyError("PRIVATE_DATABASE_UNAVAILABLE") from None
    return path
